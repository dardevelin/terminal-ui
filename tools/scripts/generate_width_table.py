#!/usr/bin/env python3
"""Write the code point width table ``Character.displayWidth`` reads.

A terminal gives each code point a column count of its own, and an app that
counts differently draws everything after the disagreement on its row in the
wrong column. The count terminals share is UAX #11's East_Asian_Width, so
the table is made from EastAsianWidth.txt, not picked by hand, and names the
version of the file it came from.

The widths are ``terminalui.width``'s, which says why for each: 0 for
nonspacing and enclosing marks and the ignorable format characters, 2 for
East_Asian_Width W and F and the regional indicators, 1 for the rest —
ambiguous (A) included. A code point the file does not list takes the
default its header gives (``DEFAULT_WIDE``, else N).

Run with a copy of the file, from
https://www.unicode.org/Public/<version>/ucd/EastAsianWidth.txt — the build
fetches nothing::

    python3 tools/scripts/generate_width_table.py EastAsianWidth.txt
    python3 tools/scripts/generate_width_table.py EastAsianWidth.txt --check

``--check`` writes nothing and exits 1 when the committed table differs
from what the file makes.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

from terminalui.width import REGIONAL_INDICATORS, ZERO_WIDTH_FORMAT, width_of  # noqa: E402

TABLE = ROOT / "Sources" / "TerminalUI" / "Rendering" / "UnicodeWidthTable.swift"
# EastAsianWidth.txt's header: unassigned code points in these blocks, and
# every undesignated one in planes 2 and 3, default to W rather than N.
DEFAULT_WIDE = ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
                (0x20000, 0x2FFFD), (0x30000, 0x3FFFD))
UNASSIGNED = "Cn"

# The file's first line names it with its version, and the table's header
# names the file it came from.
VERSION = re.compile(r"EastAsianWidth-(\d+\.\d+\.\d+)\.txt")
DATA_LINE = re.compile(
    r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)\s*#\s*(\S+)")
TABLE_ENTRY = re.compile(r"ScalarWidthRange\(0x([0-9A-F]+), 0x([0-9A-F]+), (\d)\)")


@dataclass(frozen=True)
class WidthRange:
    first: int
    last: int
    width: int


def parse(text: str) -> tuple[str, dict[int, int]]:
    """The file's version, and the width of every code point that is not 1."""
    match = VERSION.search(text)
    if match is None:
        raise ValueError("no 'EastAsianWidth-<version>.txt' line: not an EastAsianWidth.txt")
    # The comment after each line gives its General_Category, as the
    # file's header says.
    listed: dict[int, tuple[str, str]] = {}
    for line in text.splitlines():
        data = DATA_LINE.match(line)
        if data is None:
            continue
        first = int(data.group(1), 16)
        last = int(data.group(2) or data.group(1), 16)
        for code in range(first, last + 1):
            listed[code] = (data.group(3), data.group(4))
    # An unlisted code point is N and unassigned, which is 1 wide, unless a
    # default or a rule of its own says otherwise.
    candidates = set(listed).union(*(range(first, last + 1) for first, last
                                     in (*DEFAULT_WIDE, *ZERO_WIDTH_FORMAT, REGIONAL_INDICATORS)))
    widths: dict[int, int] = {}
    for code in sorted(candidates):
        value, category = listed.get(code, (default_width(code), UNASSIGNED))
        width = width_of(code, value, category)
        if width != 1:
            widths[code] = width
    return match.group(1), widths


def default_width(code: int) -> str:
    return "W" if any(first <= code <= last for first, last in DEFAULT_WIDE) else "N"


def ranges(widths: dict[int, int]) -> list[WidthRange]:
    """Consecutive code points of one width, merged."""
    merged: list[WidthRange] = []
    for code in sorted(widths):
        width = widths[code]
        if merged and merged[-1].last == code - 1 and merged[-1].width == width:
            merged[-1] = WidthRange(merged[-1].first, code, width)
        else:
            merged.append(WidthRange(code, code, width))
    return merged


def render(version: str, table: list[WidthRange]) -> str:
    entries = "\n".join(f"        ScalarWidthRange(0x{entry.first:04X}, 0x{entry.last:04X}, {entry.width}),"
                        for entry in table)
    return f"""\
// Generated by tools/scripts/generate_width_table.py from
// EastAsianWidth-{version}.txt (Unicode {version}, UAX #11). Do not edit:
// regenerate from the file, which that script's docstring says where to get.
//
// Every code point whose terminal width is not 1: 0 for General_Category Mn
// and Me and the ignorable format characters, 2 for East_Asian_Width W and
// F and the regional indicators. Ambiguous (A) is left at 1. The rules, and
// why each, are tools/terminalui/width.py's.

extension Character {{
    /// Sorted and disjoint, adjacent code points of one width in one
    /// range, for ``scalarWidth(_:)`` to binary-search.
    static let scalarWidthRanges: [ScalarWidthRange] = [
{entries}
    ]
}}
"""


def parse_table(source: str) -> tuple[str, list[WidthRange]]:
    """The version and ranges a rendered table holds — for the tests."""
    match = VERSION.search(source)
    if match is None:
        raise ValueError("the table names no EastAsianWidth-<version>.txt")
    return match.group(1), [WidthRange(int(first, 16), int(last, 16), int(width))
                            for first, last, width in TABLE_ENTRY.findall(source)]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("east_asian_width", type=Path, help="a copy of EastAsianWidth.txt")
    parser.add_argument("--output", type=Path, default=TABLE, help="the Swift file to write")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if the output differs from what the file makes")
    args = parser.parse_args(argv)
    version, widths = parse(args.east_asian_width.read_text(encoding="utf-8"))
    table = ranges(widths)
    source = render(version, table)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != source:
            print(f"{args.output} is not what EastAsianWidth-{version}.txt makes: regenerate it",
                  file=sys.stderr)
            return 1
        print(f"{args.output} matches EastAsianWidth-{version}.txt ({len(table)} ranges)")
        return 0
    args.output.write_text(source, encoding="utf-8")
    print(f"wrote {args.output}: {len(table)} ranges from EastAsianWidth-{version}.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
