/// 5x7 dot-matrix font for terminal rendering.
/// Each glyph is a 7-row array of strings where `#` = dot on, `.` = dot off.
/// Covers ASCII printable characters (space through ~).
///
/// Usage:
/// ```
/// let glyph = DotFont.glyph(for: "A")
/// // glyph[0] = ".###."
/// // glyph[1] = "#...#"
/// // ...
/// ```
public enum DotFont {

    /// Height of all glyphs in dot rows.
    public static let glyphHeight = 7

    /// Get the glyph pattern for a character. Returns `?` glyph for unknown chars.
    public static func glyph(for character: Character) -> [String] {
        let key = character == " " ? " " : String(character).uppercased()
        return glyphs[key] ?? glyphs["?"] ?? fallbackGlyph
    }

    /// Width of a glyph in dot columns.
    public static func glyphWidth(for character: Character) -> Int {
        glyph(for: character)[0].count
    }

